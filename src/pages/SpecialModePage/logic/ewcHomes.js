export const ewcHomeOf = (team) => {
    const code = EWC_TEAM_HOMES[team?.key];
    const country = code ? EWC_COUNTRIES[code] : null;
    if (!country) return null;
    const language = EWC_LANGUAGES[country.language];
    const hq = EWC_TEAM_CITIES[team.key] ?? null;
    return { code, country: country.name, flag: country.flag, languageCode: country.language, language: language.name, motto: language.motto, hq };
};


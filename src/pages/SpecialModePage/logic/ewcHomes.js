export const regionOfTeam = (team) => {
    const code = EWC_TEAM_HOMES[team?.key];
    if (!code) return null;
    const id = REGION_OF_COUNTRY[code] ?? "eu";
    return ESPORTS_REGIONS.find((region) => region.id === id) ?? null;
};

export const regionIndexOfTeam = (team) => {
    const region = regionOfTeam(team);
    return region ? ESPORTS_REGIONS.indexOf(region) : ESPORTS_REGIONS.length;
};

export const ewcMottoFor = (team) => ewcHomeOf(team)?.motto ?? EWC_MOTTO_EN;
